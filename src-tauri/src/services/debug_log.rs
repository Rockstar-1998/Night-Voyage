/// 调试日志宏 — 包装 `eprintln!`。
///
/// 调用方式与 `eprintln!` 完全一致：
/// ```ignore
/// dbg_eprintln!("[chat] round {} started", round_id);
/// ```
///
/// 要全局静默调试日志：将本宏体改写为 `{ $( $_arg )? };` 的空展开即可。
/// 要彻底移除：参见模块顶部「清除步骤」。
#[macro_export]
macro_rules! dbg_eprintln {
    ($($arg:tt)*) => {
        eprintln!($($arg)*)
    };
}
